FIRST, LAST = 32, 95


def glyph_rows(ch):
    """8x8 colour indices for one font tile."""
    cell = [[0] * 8 for _ in range(8)]
    if ch in ICONS:
        for y, row in enumerate(ICONS[ch]):
            for x, c in enumerate(row[:8]):
                if c in '123':
                    cell[y][x] = int(c)
        return cell
    rows = GLYPHS.get(ch)
    if rows is None:
        rows = GLYPHS['?']
    ink = [[False] * 8 for _ in range(8)]
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == '#':
                ink[y][x] = True
    for y in range(8):
        for x in range(8):
            if ink[y][x]:
                cell[y][x] = 3 if y < 4 else 2
            elif y and x and ink[y - 1][x - 1]:
                cell[y][x] = 1
    return cell


def font_tiles():
    return [glyph_rows(chr(c)) for c in range(FIRST, LAST + 1)]
